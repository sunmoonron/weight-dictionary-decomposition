"""Regenerate the left panel of Figure 1 (GPT-2 reconstruction against sparsity) on the typical states,
from the per-token records written by exp_a_wdd (weight, random, activation and PCA dictionaries) and
exp_d_provenance (the rotated dictionary). Sink states are those above ten times the median norm, as in
exp_z2_recompute. Rewrites the block between the FIG1 markers in wdd_tmlr.tex."""
import os, pathlib
import numpy as np
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'results')
A = np.load(os.path.join(R, 'exp_a_tokens.npz')); D = np.load(os.path.join(R, 'exp_d_tokens.npz'))
KS = [4, 8, 16, 32, 64]
x2 = A['xnorm2_L6'].astype(np.float64); nrm = np.sqrt(x2); med = np.median(nrm); typ = nrm <= 10 * med
assert (nrm > 5 * med).sum() == (nrm > 10 * med).sum()
x2d = D['xnorm2'].astype(np.float64)
assert np.allclose(x2, x2d, rtol=1e-3), 'exp_a and exp_d evaluate different states'
def curve(npz, name):
    return {k: float(npz[f'{name}_k{k}'][typ].sum() / x2[typ].sum()) for k in KS}
def curve_all(npz, name):
    return {k: float(npz[f'{name}_k{k}'].sum() / x2.sum()) for k in KS}
C = {'random': curve(A, 'random_L6'), 'pca': curve(A, 'pca_L6'), 'wdd': curve(A, 'weight_L6'), 'act': curve(A, 'actdict_L6'), 'rot': curve(D, 'wdd_rotated')}
coords = lambda c: ''.join(f'({k},{c[k]:.3f})' for k in KS)
lines = [
    '% FIG1-BEGIN (regenerated by tools/fig1.py from exp_a_tokens.npz and exp_d_tokens.npz; do not edit by hand)',
    '\\addplot[thick, color=black!40, dashed] coordinates\n  {%s};' % coords(C['random']),
    '\\addplot[thick, color=red!70!black, dashed] coordinates\n  {%s};' % coords(C['rot']),
    '\\addplot[thick, color=teal] coordinates\n  {%s};' % coords(C['pca']),
    '\\addplot[very thick, color=blue!70!black, mark=*, mark size=1.6pt] coordinates\n  {%s};' % coords(C['wdd']),
    '\\addplot[thick, color=orange!80!black] coordinates\n  {%s};' % coords(C['act']),
    '% FIG1-END',
]
p = pathlib.Path(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'wdd_tmlr.tex')); s = p.read_text()
i = s.index('% FIG1-BEGIN'); j = s.index('% FIG1-END\n') + len('% FIG1-END\n')
p.write_text(s[:i] + '\n'.join(lines) + '\n' + s[j:])
print('figure 1 left regenerated on typical states (%d of %d states):' % (typ.sum(), len(typ)))
for n, c in C.items(): print(f"  {n:7}", ' '.join(f"k{k}={c[k]:.3f}" for k in KS), '| all-state', ' '.join(f"k{k}={v:.3f}" for k, v in (curve_all(A, {'random': 'random_L6', 'pca': 'pca_L6', 'wdd': 'weight_L6', 'act': 'actdict_L6'}[n]) if n != 'rot' else curve_all(D, 'wdd_rotated')).items()))
